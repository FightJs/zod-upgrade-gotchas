async (page) => {
  await page.goto('http://127.0.0.1:4173/');
  await page.reload();
  const check = (ok, label) => { if (!ok) throw new Error(label); };
  const text = id => page.locator('#' + id).textContent();
  check(await page.locator('#source a').getAttribute('href') === 'https://github.com/FightJs/zod-upgrade-gotchas', 'real source repository link');
  const staleCleared = async () => {
    check(await page.locator('#copy').isDisabled(), 'copy disabled on edits');
    for (const version of [3, 4]) {
      check(await text('status-' + version) === 'Not run', 'both stale badges cleared');
      check(await text('result-' + version) === '—', 'both stale outputs cleared');
    }
    check((await text('input-status')).includes('Input changed'), 'rerun notice on edits');
  };
  check(JSON.stringify(JSON.parse(await text('result-3'))) === '{"b":"changed"}', 'default v3 output');
  check(JSON.stringify(JSON.parse(await text('result-4'))) === '{"a":"a","b":"changed"}', 'default v4 output');
  await page.getByRole('textbox', { name: 'JSON input', exact: true }).fill('{"a":"x","b":"y"}');
  await staleCleared();
  await page.getByRole('button', { name: 'Run both versions' }).click();
  check(await text('result-3') === await text('result-4'), 'equal control outputs');
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.getByRole('button', { name: 'Copy reproduction code' }).click();
  const code = await page.evaluate(() => navigator.clipboard.readText());
  check(code.includes('npm:zod@3.25.76') && code.includes('npm:zod@4.6.7') && code.includes('x'), 'real clipboard contains reproduction');
  await page.getByRole('button', { name: 'Share case' }).click();
  const link = await page.evaluate(() => navigator.clipboard.readText());
  check(link === 'http://127.0.0.1:4173/#case=default-partial', 'share only fixed ID');
  await page.goto(link);
  await page.reload();
  check(JSON.parse(await page.locator('#input').inputValue()).b === 'changed', 'share restores default instead of edits');
  await page.locator('#input').fill('{');
  await page.getByRole('button', { name: 'Run both versions' }).click();
  check((await text('input-status')).includes('Invalid JSON'), 'invalid JSON feedback');
  check(await page.locator('#copy').isDisabled(), 'invalid input cannot copy');
  check(await text('result-3') === '—' && await text('result-4') === '—', 'invalid results removed');
  await page.locator('#input').fill('"' + '界'.repeat(7000) + '"');
  await page.getByRole('button', { name: 'Run both versions' }).click();
  check((await text('input-status')).includes('20 KiB'), 'byte limit in browser');
  await page.locator('#input').fill('['.repeat(21) + '0' + ']'.repeat(21));
  await page.getByRole('button', { name: 'Run both versions' }).click();
  check((await text('input-status')).includes('depth'), 'depth limit in browser');
  const payload = '<img src=x onerror="globalThis.pwned=true"><script>globalThis.pwned=true</script>';
  await page.locator('#input').fill(JSON.stringify({ b: payload }));
  await page.getByRole('button', { name: 'Run both versions' }).click();
  check(JSON.parse(await text('result-3')).b === payload, 'HTML displayed as text');
  check(await page.locator('.results img, .results script').count() === 0, 'no injected elements');
  check(await page.evaluate(() => !globalThis.pwned), 'payload not executed');
  await page.getByRole('button', { name: 'Restore default' }).click();
  check(JSON.parse(await page.locator('#input').inputValue()).b === 'changed', 'restore default input');
  check(JSON.parse(await text('result-4')).a === 'a', 'restore auto-runs');
  await page.getByRole('button', { name: '02 The safe integer boundary' }).click();
  check(await text('status-3') === 'Passed' && await text('status-4') === 'Failed', 'integer actual outcome');
  await page.locator('#input').fill('42');
  await staleCleared();
  await page.getByRole('button', { name: 'Run both versions' }).click();
  check(await text('result-3') === '42' && await text('result-4') === '42', 'integer equal control');
  await page.getByRole('button', { name: '03 Enum keys become exhaustive' }).click();
  check(await text('status-3') === 'Passed' && await text('status-4') === 'Failed', 'enum actual outcome');
  await page.reload();
  check((await text('question')).includes('missing key'), 'fixed case refresh');
  await page.locator('#input').fill('{"a":1,"b":2}');
  await staleCleared();
  await page.getByRole('button', { name: 'Run both versions' }).click();
  check(await text('result-3') === await text('result-4'), 'enum equal control');
  await page.evaluate(() => Object.defineProperty(navigator.clipboard, 'writeText', { configurable: true, value: async () => { throw new Error('denied'); } }));
  await page.getByRole('button', { name: 'Copy reproduction code' }).click();
  check(await page.locator('#fallback').isVisible(), 'clipboard failure fallback');
  check((await page.locator('#copy-text').inputValue()).includes('npm:zod@4.6.7'), 'selectable fallback contains code');
  check(await page.evaluate(() => document.activeElement.id === 'copy-text' && document.activeElement.selectionEnd > 0), 'fallback focused and selected');
  await page.getByRole('button', { name: 'Share case' }).click();
  check((await page.locator('#copy-text').inputValue()).endsWith('#case=enum-record'), 'share clipboard failure fallback');
  await page.goto('http://127.0.0.1:4173/#case=unknown');
  check((await text('input-status')).includes('Unknown case'), 'unknown link notice');
  check(page.url().endsWith('#case=default-partial'), 'unknown link canonicalized');
  await page.locator('#input').focus();
  await page.keyboard.press('Tab');
  check(await page.evaluate(() => document.activeElement.textContent.includes('Run both versions')), 'keyboard reaches run');
  await page.keyboard.press('Enter');
  check((await text('input-status')).includes('Ran both'), 'keyboard runs input');
  await page.getByRole('button', { name: '02 The safe integer boundary' }).focus();
  await page.keyboard.press('Enter');
  check(page.url().endsWith('#case=integer-range'), 'keyboard switches case');
  await page.setViewportSize({ width: 1280, height: 1040 });
  await page.getByRole('button', { name: '01 Defaults after .partial()' }).click();
  await page.screenshot({ path: 'output/playwright/desktop.png', fullPage: true });
  for (const width of [375, 320]) {
    await page.setViewportSize({ width, height: 812 });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no narrow overflow at ' + width);
    const left = await page.locator('.result').nth(0).boundingBox();
    const right = await page.locator('.result').nth(1).boundingBox();
    check(right.y > left.y + left.height, 'stacked results at ' + width);
    await page.getByRole('button', { name: 'Copy reproduction code' }).click();
  }
  await page.screenshot({ path: 'output/playwright/mobile.png', fullPage: true });
  return 'PASS: edit/stale/run/reset, 3 default cases + equal controls, actual clipboard + denial fallback, private fixed share + refresh + unknown ID, invalid/size/depth, HTML safety, keyboard, 375/320px stacking and no overflow.';
}
